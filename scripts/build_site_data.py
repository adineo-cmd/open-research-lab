#!/usr/bin/env python3
"""build_site_data.py — regenerate docs/data.js from the repository's own record.

Sources:
  site/content.json                       curated showcase copy
  open-discovery-lab/FINDINGS.md          the 77 dated findings ledger
  */results/certificates/*.json           machine-checkable certificates
  git log                                 recent activity for the register

The generated docs/data.js is a single `window.SITE_DATA = {...}` assignment,
so the static site needs no fetch and works from file:// as well as Pages.
"""
import json
import os
import re
import subprocess
from collections import Counter
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return f.read()


def parse_findings(text):
    findings = []
    for line in text.splitlines():
        if not line.startswith("| F-"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4:
            continue
        fid, date, track = cells[0], cells[1], cells[2]
        body = cells[3]
        m = re.search(r"\*\*(.+?)\*\*", body, re.S)
        title = re.sub(r"\s+", " ", (m.group(1) if m else body)).strip()
        detail = re.sub(r"\*\*", "", body)
        detail = re.sub(r"\s+", " ", detail).strip()
        findings.append({
            "id": fid,
            "date": date,
            "track": track,
            "title": title,
            "detail": detail,
        })
    return findings


def count_certificates():
    total = 0
    by_track = {}
    for dirpath, dirnames, filenames in os.walk(ROOT):
        if ".git" in dirpath or "node_modules" in dirpath:
            continue
        if os.path.basename(dirpath) == "certificates":
            n = len([f for f in filenames if f.endswith(".json")])
            if n:
                rel = os.path.relpath(dirpath, ROOT).split(os.sep)[0]
                by_track[rel] = by_track.get(rel, 0) + n
                total += n
    return total, by_track


def recent_commits(n=6):
    try:
        out = subprocess.check_output(
            ["git", "-C", ROOT, "log", "-n", str(n), "--date=short",
             "--pretty=format:%h|%ad|%s"], text=True)
        return [dict(zip(("hash", "date", "subject"), l.split("|", 2)))
                for l in out.splitlines()]
    except Exception:
        return []


def main():
    content = json.loads(read("site/content.json"))
    findings = parse_findings(read("open-discovery-lab/FINDINGS.md"))
    certs, by_track = count_certificates()

    tracks = Counter(f["track"] for f in findings)
    dates = sorted(f["date"] for f in findings if re.match(r"\d{4}-\d{2}-\d{2}", f["date"]))
    span = f"{dates[0]} – {dates[-1]}" if dates else "—"
    if len(dates) >= 2:
        days = (datetime.strptime(dates[-1], "%Y-%m-%d") -
                datetime.strptime(dates[0], "%Y-%m-%d")).days + 1
    else:
        days = 1

    data = {
        "meta": content["meta"],
        "stats": {
            "findings": len(findings),
            "certificates": certs,
            "certificatesByTrack": by_track,
            "tracks": len(content["tracks"]),
            "apps": len(content["apps"]["items"]),
            "dateSpan": span,
            "daysOfWork": days,
            "generated": datetime.now().strftime("%Y-%m-%d"),
        },
        "trackCounts": dict(tracks),
        "now": content["now"],
        "tracks": content["tracks"],
        "librephone": content["librephone"],
        "apps": content["apps"],
        "method": content["method"],
        "findings": findings,
        "commits": recent_commits(),
    }
    out = os.path.join(ROOT, "docs", "data.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by scripts/build_site_data.py — do not edit by hand. */\n")
        f.write("window.SITE_DATA = ")
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write(";\n")
    print(f"wrote {out}: {len(findings)} findings, {certs} certificates")


if __name__ == "__main__":
    main()
