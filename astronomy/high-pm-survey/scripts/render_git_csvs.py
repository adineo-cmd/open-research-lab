#!/usr/bin/env python3
"""render_git_csvs.py — compact renders of the v2 vetting outputs for git.

The lab-local full-fidelity files (results/vetting_v2.csv,
results/possible_new_final.csv, produced by vet2.py finalize) keep 5-decimal
positions and long match names. The git budget (<=200 KB per file) is met by
these compact renders, which keep EVERY row and all evidence fields:

  results/vetting_v2.csv     all 1,385 candidates: rank, source_id, status
                             (K/P), confidence (A/B/C), match rule + name,
                             margin, query-coverage counters, wise/gcns codes
  results/possible_new_final.csv  the 621 survivors with ra/dec at 2016.0,
                             2000.0 and 2026.86 (5 decimals), pm, dist, G,
                             bp_rp, H, parallax S/N, per-check evidence

Full fidelity is regenerated by `python3 scripts/vet2.py finalize` +
`python3 scripts/apply_lit_checks.py` from results/vetting_v2_state.json.

Usage: python3 render_git_csvs.py
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results")
STATE = os.path.join(RES, "vetting_v2_state.json")
CANDS = os.path.join(RES, "candidates.csv")

WISE_CODE = {"catwise-match": "C", "no-catwise-match": "N"}


def _r(v, nd=5):
    try:
        return round(float(v), nd)
    except (TypeError, ValueError):
        return ""
GCNS_CODE = {"none-within-10as": "N"}


def render_vetting(state, cands):
    fields = ["rank", "source_id", "status", "conf", "rule", "match_name",
              "pm_tot", "dist_pc", "H_rpm", "margin", "n_hits", "n_hits_now",
              "ident", "wise", "gcns"]
    out = []
    for sid, rec in state.items():
        c = cands[sid]
        out.append({
            "rank": c["rank"], "source_id": sid,
            "status": rec.get("status", "?"),
            "conf": rec.get("conf", ""),
            "rule": rec.get("match_rule", "")[:8],
            "match_name": rec.get("match_name", "")[:20],
            "pm_tot": rec.get("pm_tot", ""),
            "dist_pc": c["dist_pc"], "H_rpm": c["H_rpm"],
            "margin": _r(rec.get("margin", ""), 1),
            "n_hits": rec.get("n_hits", ""), "n_hits_now": rec.get("n_hits_now", ""),
            "ident": rec.get("ident", ""),
            "wise": WISE_CODE.get(rec.get("wise", ""), (rec.get("wise", "") or "?")[:1].upper()),
            "gcns": GCNS_CODE.get(rec.get("gcns_near", ""), (rec.get("gcns_near", "") or "")[:1].upper() or "?"),
        })
    out.sort(key=lambda r: r["rank"])
    path = os.path.join(RES, "vetting_v2.csv")
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(out)
    return path, os.path.getsize(path)


def render_possible_new(state, cands):
    fields = ["source_id", "ra2016", "dec2016", "ra2000", "dec2000", "ranow",
              "decnow", "pm_tot", "plx_sn", "dist_pc", "G", "bp_rp", "H_rpm",
              "hits2000", "hitsnow", "margin_x", "ident", "wise", "cw_id",
              "cw_sep_as", "cw_w1w2", "cw_pm_ratio", "gcns", "ls", "lit",
              "conf"]
    out = []
    for sid, rec in state.items():
        if rec.get("status") != "P":
            continue
        c = cands[sid]
        ls = rec.get("ls_cutout", "")
        ls = ls.split("(")[0] if ls else ""
        out.append({
            "source_id": sid,
            "ra2016": c["ra5"], "dec2016": c["dec5"],
            "ra2000": _r(rec.get("ra2000", "")), "dec2000": _r(rec.get("dec2000", "")),
            "ranow": _r(rec.get("ranow", "")), "decnow": _r(rec.get("decnow", "")),
            "pm_tot": rec.get("pm_tot", ""),
            "plx_sn": rec.get("plx_sn", ""), "dist_pc": c["dist_pc"],
            "G": c["G2"], "bp_rp": c["bp2"], "H_rpm": c["H_rpm"],
            "hits2000": rec.get("n_hits", ""), "hitsnow": rec.get("n_hits_now", ""),
            "margin_x": rec.get("margin", ""),
            "ident": rec.get("ident", ""), "wise": rec.get("wise", ""),
            "cw_id": rec.get("cw_id", ""), "cw_sep_as": rec.get("cw_sep_as", ""),
            "cw_w1w2": rec.get("cw_w1w2", ""), "cw_pm_ratio": rec.get("cw_pm_ratio", ""),
            "gcns": GCNS_CODE.get(rec.get("gcns_near", ""), rec.get("gcns_near", "")),
            "ls": ls, "lit": rec.get("lit_check", "").split(" [")[0],
            "conf": rec.get("conf", ""),
        })
    out.sort(key=lambda r: -float(r["H_rpm"]) if r["H_rpm"] else 0.0)
    path = os.path.join(RES, "possible_new_final.csv")
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(out)
    return path, os.path.getsize(path)


def main():
    state = json.load(open(STATE))
    cands = {}
    for i, c in enumerate(csv.DictReader(open(CANDS)), 1):
        cands[c["source_id"]] = {
            "rank": i, "dist_pc": c["dist_pc"], "H_rpm": c["H_rpm"],
            "ra5": f"{float(c['ra']):.5f}", "dec5": f"{float(c['dec']):.5f}",
            "G2": f"{float(c['G']):.2f}", "bp2": f"{float(c['bp_rp']):.2f}",
        }
    # per-candidate conf comes from the full-fidelity vetting CSV written by
    # finalize() (kept locally as *_full.csv; compact renders take the
    # canonical filenames for git)
    conf_by_sid = {}
    for fn in ("vetting_v2_full.csv", "vetting_v2.csv"):
        p = os.path.join(RES, fn)
        if os.path.exists(p):
            for r in csv.DictReader(open(p)):
                conf_by_sid[r["source_id"]] = (r.get("conf", ""),
                                               r.get("status", ""))
            break
    for sid, rec in state.items():
        cf, st = conf_by_sid.get(sid, ("", ""))
        rec["conf"] = cf
        rec["status"] = rec.get("status", st)
    p1, s1 = render_vetting(state, cands)
    p2, s2 = render_possible_new(state, cands)
    print(f"{p1}: {s1} bytes")
    print(f"{p2}: {s2} bytes")


if __name__ == "__main__":
    main()
